const $=s=>document.querySelector(s);

const money=n=>`S/ ${Number(n).toFixed(2)}`;

let current=null;

let cart=JSON.parse(
    localStorage.getItem("puraSelvaCart")||"[]"
);

const cat=$("#categories");
const prod=$("#products");
const grid=$("#categoryGrid");
const pg=$("#productGrid");

/* CATEGORÍAS */

function cats(){

    grid.innerHTML="";

    Object.entries(M).forEach(([n,d])=>{

        let b=document.createElement("button");

        b.className="categoryCard";

        b.innerHTML=`
            <span class="icon">${d.i}</span>
            <span class="arrow">→</span>
            <h2>${n}</h2>
            <p>${d.p.length} opciones · ${d.s}</p>
        `;

        b.onclick=()=>openCat(n);

        grid.appendChild(b);

    });
}

/* ABRIR CATEGORÍA */

function openCat(n){

    current=n;

    cat.classList.remove("active");

    prod.classList.add("active");

    $("#backBtn").hidden=false;

    $("#catTitle").textContent=n;

    $("#catSub").textContent=M[n].s;

    $("#catIcon").textContent=M[n].i;

    $("#search").value="";

    render(M[n].p);
}

/* MOSTRAR PRODUCTOS */

function render(items){

    pg.innerHTML="";

    items.forEach(x=>{

        let [n,p,d,img]=x;

        let c=document.createElement("article");

        c.className="productCard";

        c.innerHTML=`
            <img
                class="photo"
                src="${img}"
                alt="${n}"
            >

            <div class="info">

                <h3>${n}</h3>

                <p class="desc">
                    ${d||"Sabor auténtico de la Amazonía."}
                </p>

                <div class="priceRow">

                    <span class="price">
                        ${money(p)}
                    </span>

                    <button class="order">
                        + PEDIR
                    </button>

                </div>

                ${
                    d==="2X 5.00"
                    ? '<span class="promo">PROMO · 2 POR S/ 5.00</span>'
                    : ""
                }

            </div>
        `;

        c.querySelector(".order").onclick=()=>add(x);

        pg.appendChild(c);

    });
}

/* AGREGAR AL CARRITO */

function add(x){

    let e=cart.find(a=>a.name===x[0]);

    if(e){
        e.qty++;
    }else{
        cart.push({
            name:x[0],
            price:x[1],
            qty:1
        });
    }

    save();

    openCart();
}

/* GUARDAR CARRITO */

function save(){

    localStorage.setItem(
        "puraSelvaCart",
        JSON.stringify(cart)
    );

    drawCart();
}

/* DIBUJAR CARRITO */

function drawCart(){

    let q=cart.reduce(
        (a,x)=>a+x.qty,
        0
    );

    let t=cart.reduce(
        (a,x)=>a+x.price*x.qty,
        0
    );

    $("#cartCount").textContent=q;

    $("#cartTotal").textContent=money(t);

    $("#cartItems").innerHTML=
        cart.length
        ?
        cart.map((x,i)=>`

            <div class="cartItem">

                <div>
                    <strong>${x.name}</strong>
                    <small>${money(x.price)} c/u</small>
                </div>

                <div class="qty">

                    <button
                        data-i="${i}"
                        data-a="m">
                        −
                    </button>

                    <b>${x.qty}</b>

                    <button
                        data-i="${i}"
                        data-a="p">
                        +
                    </button>

                </div>

            </div>

        `).join("")
        :
        `
        <div class="empty">
            Tu pedido está vacío 🌿
            <br>
            Agrega algo delicioso.
        </div>
        `;

    document
        .querySelectorAll(".qty button")
        .forEach(b=>{

            b.onclick=()=>{

                let i=+b.dataset.i;

                if(b.dataset.a==="p"){

                    cart[i].qty++;

                }else{

                    cart[i].qty--;

                    if(cart[i].qty<=0){

                        cart.splice(i,1);

                    }

                }

                save();

            };

        });
}

/* ABRIR CARRITO */

function openCart(){

    $("#drawer").classList.add("open");

    $("#overlay").classList.add("show");
}

/* CERRAR CARRITO */

function closeCart(){

    $("#drawer").classList.remove("open");

    $("#overlay").classList.remove("show");
}

/* VOLVER */

$("#backBtn").onclick=()=>{

    prod.classList.remove("active");

    cat.classList.add("active");

    $("#backBtn").hidden=true;

    current=null;

    scrollTo(0,0);
};

/* BUSCAR */

$("#search").oninput=e=>{

    let q=e.target.value.toLowerCase();

    render(
        M[current].p.filter(
            x=>x[0].toLowerCase().includes(q)
        )
    );
};

/* CARRITO */

$("#cartBtn").onclick=openCart;

$("#closeCart").onclick=closeCart;

$("#overlay").onclick=closeCart;

/* VACIAR */

$("#clearCart").onclick=()=>{

    cart=[];

    save();

};

